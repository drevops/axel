import fc from 'fast-check';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { gtm } from '../../src/adapters/gtm.js';
import { Axel } from '../../src/core/core.js';
import { resolveUrl } from '../../src/core/dom.js';
import { loadFixture, runStep } from '../helpers.js';

// Only this token is searched for in the events, so random text around it
// can't collide with a label by chance.
const MARKER = 'AxelPrivate7f3c9e';

const CONTACT_SCHEMES = ['mailto:', 'tel:', 'sms:'];

const ALL_TYPES = ['click', 'form_start', 'field_complete'];

const secret = fc
  .tuple(fc.string({ unit: 'binary', maxLength: 12 }), fc.string({ unit: 'binary', maxLength: 12 }))
  .map(([before, after]) => `${before}${MARKER}${after}`);

const urlWithQuery = fc
  .record({
    base: fc.oneof(fc.webUrl({ authoritySettings: { withIPv4: true, withIPv6: true, withPort: true } }), fc.webPath()),
    query: fc.webQueryParameters(),
    fragment: fc.option(
      fc.webFragments().map((fragment) => `#${fragment}`),
      { nil: '' },
    ),
  })
  .map(({ base, query, fragment }) => `${base}?token=${MARKER}&${query}${fragment}`);

const contactUrl = fc
  .record({
    scheme: fc.mixedCase(fc.constantFrom(...CONTACT_SCHEMES)),
    address: fc.oneof(fc.emailAddress(), fc.stringMatching(/^\+?[\d ()-]{3,15}$/), fc.string({ unit: 'binary' })),
    query: fc.option(
      fc.webQueryParameters().map((query) => `?${query}`),
      { nil: '' },
    ),
  })
  .map(({ scheme, address, query }) => `${scheme}${MARKER}${address}${query}`);

const attributeValue = fc.oneof(
  fc.string({ unit: 'binary' }),
  fc
    .tuple(fc.constantFrom('', ...CONTACT_SCHEMES, 'http://', 'https://example.com/?', '//', '?', '#', 'javascript:', 'data:'), fc.string({ unit: 'binary' }))
    .map(([prefix, rest]) => `${prefix}${rest}`),
);

/**
 * Parse a value the way a browser resolves a URL attribute.
 *
 * @param {string} value - The attribute value.
 * @return {URL|undefined} The URL, or undefined when the value isn't one.
 */
function parse(value) {
  try {
    return new URL(value, document.baseURI);
  } catch {
    return undefined;
  }
}

/**
 * Run an interaction with a fresh instance and return the events it sent.
 *
 * @param {object}   settings    - Overrides for DEFAULT_SETTINGS.
 * @param {Function} interaction - The interaction.
 * @return {object[]} The events pushed to the data layer.
 */
function record(settings, interaction) {
  window.dataLayer = [];

  const axel = new Axel({ adapter: gtm, ...settings }).init();

  try {
    interaction();
  } finally {
    axel.destroy();
  }

  return window.dataLayer;
}

/**
 * Point the link, the submit button's form and the marked form of the URL
 * privacy case at the same URL, then click and focus them.
 *
 * @param {string}  url      - The URL.
 * @param {boolean} fullUrls - The 'fullUrls' setting.
 * @return {Array<string|undefined>} The 'link_url' of the link and the button,
 *   then the 'form_destination' of the form.
 */
function sendUrl(url, fullUrls = false) {
  const link = document.querySelector('#privacy-url-query');
  const button = document.querySelector('#privacy-url-submit');
  const field = document.querySelector('#privacy-url-field');

  link.setAttribute('href', url);
  button.form.setAttribute('action', url);
  field.form.setAttribute('action', url);

  const events = record({ types: ALL_TYPES, fullUrls }, () => {
    link.click();
    button.click();
    field.focus();
    field.blur();
  });

  expect(events.map((event) => event.event)).toEqual(['privacy_click', 'privacy_click', 'form_start']);

  return [events[0].link_url, events[1].link_url, events[2].form_destination];
}

/**
 * Build a marked form with 1 field the visitor fills in or chooses.
 *
 * The visitor's answer is the typed value, a chosen option, or the label and
 * value of a radio or checkbox; the question is 'Question'.
 *
 * @param {object} spec - The field, as generated by the property.
 * @return {HTMLFormElement} The form.
 */
function buildForm({ kind, inputType, labelling, inFieldset, rendered }) {
  const form = document.createElement('form');
  const isChoice = kind === 'radio' || kind === 'checkbox';
  let field;

  form.id = 'property-form';
  form.setAttribute('data-axel-form', 'private');

  if (kind === 'textarea') {
    field = document.createElement('textarea');
    field.textContent = rendered;
  } else if (kind === 'select') {
    field = document.createElement('select');
    field.append(new Option('Other', 'other'), new Option(rendered, rendered));
  } else {
    field = document.createElement('input');
    field.type = isChoice ? kind : inputType;

    if (isChoice) {
      field.value = rendered;
    }
  }

  field.id = 'property-field';
  field.name = 'answer';

  // A checkbox outside a fieldset is named by its own label, which is then the
  // question rather than the answer.
  const container = inFieldset || kind === 'checkbox' ? document.createElement('fieldset') : form;

  if (container !== form) {
    const legend = document.createElement('legend');

    legend.textContent = 'Question';
    container.append(legend);
    form.append(container);
  }

  const label = document.createElement('label');

  label.textContent = isChoice ? rendered : 'Question';

  if (labelling === 'for') {
    label.htmlFor = 'property-field';
    container.append(field, label);
  } else if (labelling === 'wrap') {
    label.append(field);
    container.append(label);
  } else {
    field.setAttribute('aria-label', 'Question');
    container.append(field);
  }

  return form;
}

describe('privacy properties', () => {
  beforeEach(() => {
    loadFixture();
    window.sessionStorage.clear();
  });

  afterEach(() => {
    delete window.dataLayer;
  });

  it('sends URLs without the query string and keeps the fragment', () => {
    fc.assert(
      fc.property(urlWithQuery, (url) => {
        const expected = parse(url);

        sendUrl(url).forEach((sent) => {
          if (expected === undefined) {
            expect(sent).toBeUndefined();

            return;
          }

          const actual = new URL(sent);

          expect(sent).not.toContain(MARKER);
          expect(actual.search).toBe('');
          expect(actual.hash).toBe(expected.hash);
          expect(`${actual.origin}${actual.pathname}`).toBe(`${expected.origin}${expected.pathname}`);
        });
      }),
    );
  });

  it('sends only the scheme of contact URLs', () => {
    fc.assert(
      fc.property(contactUrl, (url) => {
        const scheme = url.slice(0, url.indexOf(':') + 1).toLowerCase();

        expect(sendUrl(url)).toEqual([scheme, scheme, scheme]);
      }),
    );
  });

  it('sends URLs as they are with the full URLs setting', () => {
    fc.assert(
      fc.property(fc.oneof(urlWithQuery, contactUrl), (url) => {
        const expected = parse(url)?.href;

        expect(sendUrl(url, true)).toEqual([expected, expected, expected]);
      }),
    );
  });

  it('resolves any attribute value without throwing and still sends the event', () => {
    const link = document.querySelector('#privacy-url-query');

    fc.assert(
      fc.property(attributeValue, (value) => {
        link.setAttribute('href', value);

        expect(() => resolveUrl(link, 'href', true)).not.toThrow();

        const expected = parse(value);
        const events = record({}, () => link.click());

        expect(events).toHaveLength(1);

        const sent = events[0].link_url;

        if (expected === undefined) {
          expect(sent).toBeUndefined();
        } else if (CONTACT_SCHEMES.includes(expected.protocol)) {
          expect(sent).toBe(expected.protocol);
        } else {
          expect(new URL(sent).search).toBe('');
          expect(new URL(sent).hash).toBe(expected.hash);
        }
      }),
    );
  });

  it('sends no typed or chosen value from a field', () => {
    const field = fc.record({
      kind: fc.constantFrom('input', 'textarea', 'select', 'radio', 'checkbox'),
      inputType: fc.constantFrom('text', 'email', 'search', 'tel', 'url', 'password'),
      labelling: fc.constantFrom('for', 'wrap', 'aria'),
      inFieldset: fc.boolean(),
      rendered: secret,
      typed: secret,
    });

    fc.assert(
      fc.property(field, (spec) => {
        document.body.replaceChildren(buildForm(spec));

        const events = record({ types: ALL_TYPES }, () => {
          if (spec.kind === 'input' || spec.kind === 'textarea') {
            runStep({ action: 'fill', target: '#property-field', value: spec.typed });
          } else if (spec.kind === 'select') {
            runStep({ action: 'select', target: '#property-field', value: spec.rendered });
          } else {
            runStep({ action: 'check', target: '#property-field' });
          }
        });

        expect(document.querySelector('#property-field').value).toContain(MARKER);
        expect(events.map((event) => event.event)).toEqual(['form_start', 'field_complete']);
        // A radio is never named by its own label, so without a legend or an
        // 'aria-label' it has no label at all.
        expect(events[1].field_label).toBe(spec.kind === 'radio' && !spec.inFieldset && spec.labelling !== 'aria' ? '' : 'Question');
        expect(JSON.stringify(events)).not.toContain(MARKER);
      }),
    );
  });

  it('adds no text from a textarea or select inside a clicked link or button', () => {
    const target = fc.record({
      tag: fc.constantFrom('a', 'button'),
      control: fc.constantFrom('textarea', 'select'),
      first: fc.boolean(),
      rendered: secret,
      typed: secret,
    });

    fc.assert(
      fc.property(target, ({ tag, control, first, rendered, typed }) => {
        const wrapper = document.createElement('div');
        const element = document.createElement(tag);
        const nested = document.createElement(control);

        wrapper.setAttribute('data-axel-event', 'property_click');
        element.id = 'property-target';
        element.setAttribute('href', '/help');

        if (control === 'textarea') {
          nested.textContent = rendered;
          nested.value = typed;
        } else {
          nested.append(new Option(rendered, rendered, true, true));
        }

        element.append(...(first ? [nested, 'Help'] : ['Help', nested]));
        wrapper.append(element);
        document.body.replaceChildren(wrapper);

        const events = record({}, () => element.click());

        expect(events).toHaveLength(1);
        expect(events[0].link_text).toBe('Help');
        expect(JSON.stringify(events)).not.toContain(MARKER);
      }),
    );
  });

  it('sends no typed value when the click selector matches a field', () => {
    const input = fc.record({
      type: fc.constantFrom('text', 'email', 'search', 'tel', 'url', 'password', 'hidden'),
      typed: secret,
    });

    fc.assert(
      fc.property(input, ({ type, typed }) => {
        const form = document.createElement('form');
        const field = document.createElement('input');

        form.setAttribute('data-axel-event', 'form_click');
        field.type = type;
        field.value = typed;
        form.append(field);
        document.body.replaceChildren(form);

        const events = record({ clickSelector: 'input' }, () => field.click());

        expect(field.value).toContain(MARKER);
        expect(events).toEqual([{ event: 'form_click', link_text: '', click_type: 'button' }]);
      }),
    );
  });
});
